/* ivs_asm: the project mini-assembler (Phase 7, D-16, D-17, A-01, A-15). It turns one source file
 * into one listing in the grammar of the committed listings (docs/diagnostics.md), so the existing
 * `listing` and `pack.words` checks police what it writes. It is a development tool: never
 * installed, never shipped, never part of the core. It reads the one source file and writes the one
 * listing file named on its command line, uses no environment variable, clock, locale or other
 * file, and its output holds no time or host-dependent byte: the only path it prints is the source
 * path the caller passed, which must be relative.
 *
 * The encoding table is hand-written from docs/cp1610/reference-notes.md and the manual pages it
 * cites; no other assembler or emulator source, table or output was used, and
 * data/cp1610/opcode-families.json is the checker's police, never read here (D-18).
 *
 * Usage:  ivs_asm <source.asm> <listing.txt>      ivs_asm --version
 * Source (A-15): ASCII and LF only (a tab is a blank, a CR is a refusal), one statement per line.
 *   # key: value        the leading block of these lines is the header, copied to the listing
 *                       unchanged; `# window: AAAA-BBBB` is required and bounds every word
 *   ; text              comment to the end of the line
 *   label:  MNEMONIC operands      the label is optional; labels are global, defined once
 *   NAME    EQU   expr             a constant; its expression may use only earlier symbols
 *           ORG   expr             sets the address; moves forward only, the gap is filled with zero
 *                                  words (row HLT, text fill); the first ORG comes before any word
 * Operands: Rn, #expr (immediate), a bare expr (direct address or branch target). An expression is
 * numbers ($ and hex digits, or decimal) and symbols joined by + and -, left to right, every partial
 * result 0 to 65535. Pass 1 gives every statement its address from syntax alone; pass 2 resolves
 * values. An immediate, a direct address or a branch displacement above 03FF is a refusal; so is a
 * spelling whose decle belongs to another leaf row (MOVR R1, R1 is TSTR R1).
 * Listing: the header lines, `# generated by ivs_asm from <path>; edit the source, not this file`,
 * one `# sym: <name> <ADDR>` line per label (never `# label:`, a header key, A-01), then one
 * `ADDR HEX4 BITS ROW ASM` line per word, with `-> ADDR` on branch and jump lines.
 * Exit status: 0 on success, 1 on any refusal: one line `ivs_asm: <token>: <source>:<line>: <detail>`
 * on stderr and no output file (the listing is written beside its target and renamed). */
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#define AS_VERSION "1"
#define AS_MAX_BYTES 131072u
#define AS_MAX_LINE 255u
#define AS_MAX_LINES 4096u
#define AS_MAX_WORDS 4096u
#define AS_MAX_SYMS 256u
#define AS_MAX_HEADER 32u
#define AS_MAX_PATH 200u
#define AS_NAME_MAX 31u
#define AS_WORD_MAX 0x03FFu
#define AS_ADDR_MAX 0xFFFFu

/* Operand shapes of the table: the letters of as_shape() say what each operand is. */
enum { AC_NONE, AC_RDST, AC_RSAME, AC_RR, AC_IMM, AC_DIRECT_OUT, AC_IND_IN, AC_BRANCH, AC_JUMP };

typedef struct as_op {
  const char *name;
  unsigned cls;
  unsigned rmax;   /* highest register number a register operand may name */
  unsigned base;   /* decle bits fixed by the mnemonic (the condition code of a branch) */
} as_op; /* the leaf row id of the first decle is the mnemonic */

/* "pdf N" is a page of the CP-1600 users manual cited by docs/cp1610/reference-notes.md. */
static const as_op as_ops[] = {
  /* internal control 0000 000 ooo (Fig. 3.3.4, pdf 51; control table, pdf 56) */
  {"HLT", AC_NONE, 0u, 0x000u},
  {"EIS", AC_NONE, 0u, 0x002u},
  {"DIS", AC_NONE, 0u, 0x003u},
  /* single register 0000 ooo DDD, GSWD is 0000 110 0DD (Fig. 3.3.3, pdf 51; tables pdf 53, pdf 56) */
  {"INCR", AC_RDST, 7u, 0x008u},
  {"DECR", AC_RDST, 7u, 0x010u},
  {"GSWD", AC_RDST, 3u, 0x030u},
  /* register to register 0 ooo SSS DDD, MOVR 010, ADDR 011 (Fig. 3.3.1, pdf 50; table pdf 53);
   * TSTR is 0010 SSS SSS and CLRR is 0111 DDD DDD (the same table) */
  {"TSTR", AC_RSAME, 7u, 0x080u},
  {"CLRR", AC_RSAME, 7u, 0x1C0u},
  {"MOVR", AC_RR, 7u, 0x080u},
  {"ADDR", AC_RR, 7u, 0x0C0u},
  /* external reference 1 ooo MMM DDD (Fig. 3.2.1, pdf 46), MVO 001, MVI 010: direct MMM 000
   * (direct table, pdf 55), indirect MMM 001..101 (indirect table, pdf 55), stack MMM 110 (PSHR is
   * MVO@ through R6 and PULR is MVI@ through R6, pdf 55), immediate MMM 111 (table pdf 57) */
  {"MVO", AC_DIRECT_OUT, 7u, 0x240u},
  {"MVI@", AC_IND_IN, 7u, 0x280u},
  {"PSHR", AC_RDST, 7u, 0x270u},
  {"PULR", AC_RDST, 7u, 0x2B0u},
  {"MVII", AC_IMM, 7u, 0x2B8u},
  {"ADDI", AC_IMM, 7u, 0x2F8u},
  /* branch 1000 S I cccc, then the displacement (Fig. 3.2.2, pdf 47; branch table, pdf 54) */
  {"B", AC_BRANCH, 0u, 0x0u},
  {"BNZE", AC_BRANCH, 0u, 0xCu},
  /* jump 0000 000 100, BB AAAAAA EE, AAAAAAAAAA (Fig. 3.3.5, pdf 52; jump table, pdf 56) */
  {"J", AC_JUMP, 0u, 0x0u},
};
#define AS_NOPS (sizeof as_ops / sizeof as_ops[0])

typedef struct as_sym {
  char name[AS_NAME_MAX + 1u];
  uint32_t value;
  int is_label;
} as_sym;

typedef struct as_state {
  char buf[AS_MAX_BYTES + 2u];
  char *line[AS_MAX_LINES];
  size_t nlines;
  size_t nhdr;
  const char *src;
  FILE *out;
  unsigned long lineno;
  int failed;
  int have_org;
  uint32_t pc;
  uint32_t nwords;
  uint32_t win_lo;
  uint32_t win_hi;
  as_sym sym[AS_MAX_SYMS];
  size_t nsym;
} as_state;

static as_state as_g;

/* The first refusal is printed, later ones are not: after it every helper returns a harmless 0
 * and the loops stop at the next statement. */
static void as_fail(const char *token, const char *what, const char *arg)
{
  if (!as_g.failed) {
    as_g.failed = 1;
    fprintf(stderr, "ivs_asm: %s: %s:%lu: %s%.40s\n", token, as_g.src, as_g.lineno, what, arg);
  }
}

static int as_digit(char c) { return c >= '0' && c <= '9'; }
static int as_idstart(char c) { return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '_'; }
static int as_idchar(char c) { return as_idstart(c) || as_digit(c); }
static int as_blank(char c) { return c == ' ' || c == '\t'; }

static int as_hexval(char c)
{
  if (as_digit(c)) {
    return c - '0';
  }
  if (c >= 'A' && c <= 'F') {
    return c - 'A' + 10;
  }
  return c >= 'a' && c <= 'f' ? c - 'a' + 10 : -1;
}

/* Four hex digits at p; 1 on success. */
static int as_hex4(const char *p, uint32_t *out)
{
  uint32_t v = 0u;
  size_t i;
  for (i = 0u; i < 4u; i++) {
    int h = as_hexval(p[i]);
    if (h < 0) {
      return 0;
    }
    v = (v << 4) | (uint32_t)h;
  }
  *out = v;
  return 1;
}

static const char *as_skip(const char *p)
{
  while (as_blank(*p)) {
    p++;
  }
  return p;
}

static void as_trim_end(char *s)
{
  size_t n = strlen(s);
  while (n > 0u && as_blank(s[n - 1u])) {
    s[--n] = '\0';
  }
}

/* R followed by digits only (R0 to R7 are registers, R8 and up are named so they are refused). */
static int as_regname(const char *s)
{
  size_t i;
  if (s[0] != 'R' || !as_digit(s[1])) {
    return 0;
  }
  for (i = 2u; s[i] != '\0'; i++) {
    if (!as_digit(s[i])) {
      return 0;
    }
  }
  return 1;
}

static const as_op *as_lookup(const char *name)
{
  size_t i;
  for (i = 0u; i < AS_NOPS; i++) {
    if (strcmp(as_ops[i].name, name) == 0) {
      return &as_ops[i];
    }
  }
  return NULL;
}

static const as_sym *as_find(const char *name)
{
  size_t i;
  for (i = 0u; i < as_g.nsym; i++) {
    if (strcmp(as_g.sym[i].name, name) == 0) {
      return &as_g.sym[i];
    }
  }
  return NULL;
}

static void as_define(const char *name, uint32_t value, int is_label)
{
  size_t n = strlen(name);
  size_t i;
  as_sym *s;
  for (i = 1u; i < n; i++) {
    if (!as_idchar(name[i])) {
      n = 0u;
    }
  }
  if (n == 0u || n > AS_NAME_MAX || !as_idstart(name[0])) {
    as_fail("asm-syntax", "bad symbol name: ", name);
  } else if (as_lookup(name) != NULL || as_regname(name) || strcmp(name, "ORG") == 0 || strcmp(name, "EQU") == 0) {
    as_fail("asm-symbol-reserved", "reserved word: ", name);
  } else if (as_find(name) != NULL) {
    as_fail("asm-symbol-duplicate", "symbol defined twice: ", name);
  } else if (as_g.nsym == AS_MAX_SYMS) {
    as_fail("asm-limit", "more than 256 symbols", "");
  } else {
    s = &as_g.sym[as_g.nsym++];
    memcpy(s->name, name, n + 1u);
    s->value = value;
    s->is_label = is_label;
  }
}

/* One term: $ and 1 to 4 hex digits, decimal digits up to 65535, or a symbol. */
static uint32_t as_term(const char **pp)
{
  const char *p = *pp;
  uint32_t v = 0u;
  if (*p == '$') {
    unsigned nd = 0u;
    int h;
    for (p++; nd <= 4u && (h = as_hexval(*p)) >= 0; p++) {
      v = (v << 4) | (uint32_t)h;
      nd++;
    }
    if (nd == 0u || nd > 4u) {
      as_fail("asm-expr", "a $ number has 1 to 4 hex digits: ", *pp);
    }
  } else if (as_digit(*p)) {
    for (; as_digit(*p) && v <= AS_ADDR_MAX; p++) {
      v = v * 10u + (uint32_t)(*p - '0');
    }
    if (v > AS_ADDR_MAX) {
      as_fail("asm-expr", "number above 65535: ", *pp);
    }
  } else if (as_idstart(*p)) {
    char name[AS_NAME_MAX + 1u];
    size_t n = 0u;
    const as_sym *s;
    for (; as_idchar(*p); p++, n++) {
      if (n < AS_NAME_MAX) {
        name[n] = *p;
      }
    }
    name[n < AS_NAME_MAX ? n : AS_NAME_MAX] = '\0';
    s = n > AS_NAME_MAX ? NULL : as_find(name);
    if (s != NULL) {
      v = s->value;
    } else {
      as_fail(n > AS_NAME_MAX ? "asm-syntax" : "asm-symbol-undefined", "no such symbol: ", *pp);
    }
  } else {
    as_fail("asm-expr", "number or symbol expected at: ", p);
  }
  *pp = p;
  return as_g.failed ? 0u : v;
}

static uint32_t as_eval(const char *s)
{
  const char *p = as_skip(s);
  uint32_t acc = as_term(&p);
  while (!as_g.failed && *(p = as_skip(p)) != '\0') {
    char op = *p;
    uint32_t t;
    if (op != '+' && op != '-') {
      as_fail("asm-expr", "operator + or - expected at: ", p);
      break;
    }
    p = as_skip(p + 1);
    t = as_term(&p);
    if (op == '+') {
      acc += t;
    } else if (t > acc) {
      as_fail("asm-expr", "value below 0: ", s);
    } else {
      acc -= t;
    }
    if (acc > AS_ADDR_MAX) {
      as_fail("asm-expr", "value above 65535: ", s);
    }
  }
  return as_g.failed ? 0u : acc;
}

/* Next blank-separated word of *sp, ended in place; *sp then points past it and its blanks. */
static char *as_next(char **sp)
{
  char *s = *sp;
  char *w;
  while (as_blank(*s)) {
    s++;
  }
  w = s;
  while (*s != '\0' && !as_blank(*s)) {
    s++;
  }
  if (*s != '\0') {
    *s++ = '\0';
    while (as_blank(*s)) {
      s++;
    }
  }
  *sp = s;
  return *w == '\0' ? NULL : w;
}

/* Splits an operand list at commas, trimming blanks; returns the count, max + 1 when there are more. */
static size_t as_split(char *s, char **v, size_t max)
{
  size_t n = 0u;
  if (*s == '\0') {
    return 0u;
  }
  for (;;) {
    char *c = strchr(s, ',');
    while (as_blank(*s)) {
      s++;
    }
    if (c != NULL) {
      *c = '\0';
    }
    as_trim_end(s);
    if (*s == '\0') {
      as_fail("asm-syntax", "empty operand", "");
      return max + 1u;
    }
    if (n == max) {
      return max + 1u;
    }
    v[n++] = s;
    if (c == NULL) {
      return n;
    }
    s = c + 1;
  }
}

/* Operands of a class, one letter each: r register, # immediate, a address or target. Pass 1 uses
 * the length only (syntax alone, D-17). */
static const char *as_shape(unsigned cls)
{
  switch (cls) {
  case AC_RDST:
  case AC_RSAME:
    return "r";
  case AC_RR:
  case AC_IND_IN:
    return "rr";
  case AC_IMM:
    return "#r";
  case AC_DIRECT_OUT:
    return "ra";
  case AC_BRANCH:
  case AC_JUMP:
    return "a";
  default:
    return "";
  }
}

static uint32_t as_words(unsigned cls)
{
  return cls == AC_JUMP ? 3u : (cls == AC_IMM || cls == AC_DIRECT_OUT || cls == AC_BRANCH) ? 2u : 1u;
}

static void as_advance(uint32_t k)
{
  if (as_g.pc + k > AS_ADDR_MAX + 1u) {
    as_fail("asm-org", "address above FFFF", "");
  } else if (as_g.nwords + k > AS_MAX_WORDS) {
    as_fail("asm-limit", "more than 4096 words", "");
  } else {
    as_g.nwords += k;
    as_g.pc += k;
  }
}

/* Prints `ADDR HEX4 BITS ROW ` of one word (BITS in the groups grp, digit counts summing to 10) and
 * advances pc; the caller prints the ASM text and the line end. */
static void as_put(unsigned word, const char *grp, const char *row)
{
  char bits[16];
  size_t k = 0u;
  unsigned left = 10u;
  if (as_g.failed) {
    return;
  }
  if (as_g.pc < as_g.win_lo || as_g.pc > as_g.win_hi) {
    as_fail("asm-window", "word address outside the header window", "");
    return;
  }
  for (; *grp != '\0'; grp++) {
    unsigned size = (unsigned)(*grp - '0');
    if (k != 0u) {
      bits[k++] = ' ';
    }
    for (; size > 0u && left > 0u; size--) {
      bits[k++] = ((word >> --left) & 1u) != 0u ? '1' : '0';
    }
  }
  bits[k] = '\0';
  fprintf(as_g.out, "%04X %04X %s %s ", (unsigned)as_g.pc, word, bits, row);
  as_g.pc++;
}

/* An operand word: its own line, row -, with a one-word note. */
static void as_opword(unsigned value, const char *grp, const char *note)
{
  as_put(value, grp, "-");
  fprintf(as_g.out, "%s %04X\n", note, value);
}

static unsigned as_reg(const char *s, unsigned rmax)
{
  unsigned r = 0u;
  if (!as_regname(s)) {
    as_fail("asm-operand-kind", "register expected: ", s);
  } else if (s[2] != '\0' || s[1] > '7') {
    as_fail("asm-register", "no such register: ", s);
  } else if ((unsigned)(s[1] - '0') > rmax) {
    as_fail("asm-register", "register not allowed here: ", s);
  } else {
    r = (unsigned)(s[1] - '0');
  }
  return r;
}

/* One operand of the shape letter sh. An immediate above 03FF would need the SDBD prefix. */
static uint32_t as_operand(char sh, unsigned rmax, const char *s)
{
  uint32_t v = 0u;
  if (sh == 'r') {
    return as_reg(s, rmax);
  }
  if ((sh == '#') != (s[0] == '#') || (sh == 'a' && as_regname(s))) {
    as_fail("asm-operand-kind", sh == '#' ? "immediate (#expr) expected: " : "address or target expected: ", s);
    return 0u;
  }
  v = as_eval(sh == '#' ? s + 1 : s);
  if (sh == '#' && v > AS_WORD_MAX) {
    as_fail("asm-imm-sdbd", "immediate above 03FF needs SDBD: ", s);
  }
  return as_g.failed ? 0u : v;
}

/* The canonical ASM text of the instruction, re-parseable as source; branches and jumps add the
 * target as `-> ADDR` (the rule of the listing checker). */
static void as_text(const as_op *op, const char *shape, const uint32_t *a)
{
  size_t k;
  fputs(op->name, as_g.out);
  for (k = 0u; shape[k] != '\0'; k++) {
    fputs(k == 0u ? " " : ", ", as_g.out);
    fprintf(as_g.out, shape[k] == 'r' ? "R%u" : shape[k] == '#' ? "#$%04X" : "$%04X", (unsigned)a[k]);
  }
  if (op->cls == AC_BRANCH || op->cls == AC_JUMP) {
    fprintf(as_g.out, " -> %04X", (unsigned)a[0]);
  }
  fputc('\n', as_g.out);
}

/* Pass 2 of one instruction statement. */
static void as_encode(const as_op *op, char *rest)
{
  const char *shape = as_shape(op->cls);
  char *v[4];
  uint32_t a[2] = {0u, 0u};
  unsigned word = op->base;
  uint32_t pc = as_g.pc;
  size_t n = as_split(rest, v, 3u);
  size_t k;
  if (as_g.failed) {
    return;
  }
  if (n != strlen(shape)) {
    as_fail("asm-operand-count", "wrong operand count for ", op->name);
    return;
  }
  for (k = 0u; k < n; k++) {
    a[k] = as_operand(shape[k], op->rmax, v[k]);
  }
  switch (op->cls) {
  case AC_RDST:
    word |= (unsigned)a[0];
    break;
  case AC_RSAME:
    word |= (unsigned)((a[0] << 3) | a[0]);
    break;
  case AC_RR:
  case AC_IND_IN:
    word |= (unsigned)((a[0] << 3) | a[1]);
    if (op->cls == AC_RR && strcmp(op->name, "MOVR") == 0 && a[0] == a[1]) {
      as_fail("asm-spelling", "this decle is TSTR, write TSTR for ", v[0]);
    } else if (op->cls == AC_RR && strcmp(op->name, "MOVR") == 0 && a[1] == 7u) {
      as_fail("asm-spelling", "this decle is JR, write JR for ", v[0]);
    } else if (op->cls == AC_IND_IN && a[0] == 0u) {
      as_fail("asm-register", "R0 is not an indirect register: ", v[0]);
    } else if (op->cls == AC_IND_IN && a[0] >= 6u) {
      as_fail("asm-spelling", a[0] == 6u ? "this decle is PULR, write PULR for " : "this decle is MVII, write MVII for ", v[0]);
    }
    break;
  case AC_IMM:
    word |= (unsigned)a[1];
    break;
  case AC_DIRECT_OUT:
    word |= (unsigned)a[0];
    if (a[1] > AS_WORD_MAX) {
      as_fail("asm-direct-range", "direct address above 03FF: ", v[1]);
    }
    break;
  case AC_BRANCH: {
    /* The formula of the listing checker: forward `target - (pc + 2)`, backward `(pc + 1) - target`
     * with S = 1 (docs/diagnostics.md; pdf 47). */
    unsigned back = a[0] >= pc + 2u ? 0u : 1u;
    uint32_t d = back == 0u ? a[0] - (pc + 2u) : pc + 1u - a[0];
    if (d > AS_WORD_MAX) {
      as_fail("asm-branch-range", "displacement above 03FF: ", op->name);
    }
    as_put(word | 0x200u | (back << 5), "424", op->name);
    as_text(op, shape, a);
    as_opword((unsigned)d, "244", back == 0u ? "displacement (S=0)" : "displacement (S=1)");
    return;
  }
  case AC_JUMP:
    as_put(0x004u, "433", op->name);
    as_text(op, shape, a);
    as_opword(0x300u | (unsigned)((a[0] >> 10) << 2) | word, "262", "second decle (BB=11, target bits 15..10, DE)");
    as_opword((unsigned)(a[0] & AS_WORD_MAX), "244", "third decle (target bits 9..0)");
    return;
  default:
    break;
  }
  as_put(word, "433", op->name);
  as_text(op, shape, a);
  if (op->cls == AC_IMM || op->cls == AC_DIRECT_OUT) {
    as_opword((unsigned)a[op->cls == AC_IMM ? 0 : 1], "244", op->cls == AC_IMM ? "immediate" : "address");
  }
}

static void as_org(unsigned pass, const char *expr)
{
  uint32_t v = as_eval(expr);
  if (as_g.failed) {
    return;
  }
  if (!as_g.have_org) {
    as_g.have_org = 1;
    as_g.pc = v;
  } else if (v < as_g.pc) {
    as_fail("asm-org", "ORG moves backward: ", expr);
  } else if (pass == 1u) {
    as_advance(v - as_g.pc);
  } else {
    while (as_g.pc < v && !as_g.failed) {
      as_put(0u, "433", "HLT");
      fputs("fill\n", as_g.out);
    }
  }
}

/* One statement (comment removed, blanks trimmed) in pass 1 or pass 2. */
static void as_stmt(unsigned pass, char *s)
{
  char *w = as_next(&s);
  char *label = NULL;
  const as_op *op;
  size_t n;
  int equ;
  if (w == NULL) {
    return;
  }
  if (w[0] == '#') {
    as_fail("asm-header", "header lines belong at the top of the source", "");
    return;
  }
  n = strlen(w);
  if (w[n - 1u] == ':') {
    w[n - 1u] = '\0';
    label = w;
    if (pass == 1u && !as_g.have_org) {
      as_fail("asm-org", "ORG must come before the first label: ", label);
    } else if (pass == 1u) {
      as_define(label, as_g.pc, 1);
    }
    if ((w = as_next(&s)) == NULL) {
      return;
    }
  }
  equ = strncmp(s, "EQU", 3u) == 0 && (s[3] == '\0' || as_blank(s[3]));
  if (equ && label == NULL) {
    uint32_t v = pass == 1u ? as_eval(s + 3) : 0u;
    if (pass == 1u && !as_g.failed) {
      as_define(w, v, 0);
    }
  } else if (strcmp(w, "ORG") == 0) {
    as_org(pass, s);
  } else if (equ || strcmp(w, "EQU") == 0) {
    as_fail("asm-syntax", "write NAME EQU expr, with no label: ", w);
  } else if ((op = as_lookup(w)) == NULL) {
    as_fail("asm-mnemonic", "unknown mnemonic ", w);
  } else if (!as_g.have_org) {
    as_fail("asm-org", "ORG must come before the first word", "");
  } else if (pass == 1u) {
    as_advance(as_words(op->cls));
  } else {
    as_encode(op, s);
  }
}

static void as_pass(unsigned pass)
{
  char work[AS_MAX_LINE + 1u];
  size_t i;
  char *c;
  as_g.pc = 0u;
  as_g.have_org = 0;
  as_g.nwords = 0u;
  for (i = as_g.nhdr; i < as_g.nlines && !as_g.failed; i++) {
    as_g.lineno = (unsigned long)i + 1ul;
    memcpy(work, as_g.line[i], strlen(as_g.line[i]) + 1u);
    if ((c = strchr(work, ';')) != NULL) {
      *c = '\0';
    }
    as_trim_end(work);
    as_stmt(pass, work);
  }
}

/* Reads the source into as_g.buf and splits it into lines; refuses CR and non-ASCII bytes. */
static int as_load(const char *path)
{
  FILE *f = fopen(path, "rb");
  size_t n = 0u;
  size_t i;
  size_t start = 0u;
  if (f != NULL) {
    n = fread(as_g.buf, 1u, AS_MAX_BYTES + 1u, f);
    if (ferror(f) != 0) {
      f = NULL;
    }
  }
  if (f == NULL || fclose(f) != 0) {
    fprintf(stderr, "ivs_asm: cannot read %s\n", path);
    as_g.failed = 1;
  } else if (n > AS_MAX_BYTES) {
    as_fail("asm-limit", "source above 131072 bytes", "");
  } else {
    as_g.buf[n] = '\0';
  }
  as_g.lineno = 1ul;
  for (i = 0u; i <= n && !as_g.failed; i++) {
    char c = i < n ? as_g.buf[i] : '\n';
    if (c == '\n' && i == n && i == start) {
      break;
    }
    if (c == '\n' && (as_g.nlines == AS_MAX_LINES || i - start > AS_MAX_LINE)) {
      as_fail("asm-limit", "more than 4096 lines or a line above 255 bytes", "");
    } else if (c == '\n') {
      as_g.buf[i] = '\0';
      as_g.line[as_g.nlines++] = as_g.buf + start;
      start = i + 1u;
      as_g.lineno++;
    } else if (c == '\r') {
      as_fail("asm-syntax", "CR byte, lines end in LF only", "");
    } else if (c != '\t' && (c < ' ' || c > '~')) {
      as_fail("asm-syntax", "byte outside printable ASCII", "");
    }
  }
  return !as_g.failed;
}

/* The leading header block: `# key: value` lines (key lower-case letters, value not empty). The
 * `window` line is required, once, as AAAA-BBBB. */
static void as_header(void)
{
  int have_window = 0;
  for (; as_g.nhdr < as_g.nlines && !as_g.failed; as_g.nhdr++) {
    const char *s = as_g.line[as_g.nhdr];
    size_t k = 2u;
    as_g.lineno = (unsigned long)as_g.nhdr + 1ul;
    while (s[0] == '#' && s[1] == ' ' && s[k] >= 'a' && s[k] <= 'z') {
      k++;
    }
    if (s[0] != '#' || s[1] != ' ' || k == 2u || s[k] != ':' || s[k + 1u] != ' ' || s[k + 2u] == '\0') {
      break;
    }
    if (as_g.nhdr == AS_MAX_HEADER) {
      as_fail("asm-limit", "more than 32 header lines", "");
    } else if (k == 8u && strncmp(s + 2, "window", 6u) == 0) {
      const char *v = s + 10;
      if (have_window || strlen(v) != 9u || v[4] != '-' || !as_hex4(v, &as_g.win_lo) || !as_hex4(v + 5, &as_g.win_hi)
          || as_g.win_lo > as_g.win_hi) {
        as_fail("asm-header", "window given twice or not AAAA-BBBB (low to high): ", v);
      }
      have_window = 1;
    }
  }
  if (!have_window && !as_g.failed) {
    as_g.lineno = 1ul;
    as_fail("asm-header", "no '# window: AAAA-BBBB' header line", "");
  }
}

/* A source path the listing may print: relative, characters A-Z a-z 0-9 . _ / - only. */
static int as_path_ok(const char *p)
{
  size_t i;
  size_t n = strlen(p);
  if (n == 0u || n > AS_MAX_PATH || p[0] == '/') {
    return 0;
  }
  for (i = 0u; i < n; i++) {
    if (!(as_idchar(p[i]) || p[i] == '.' || p[i] == '/' || p[i] == '-')) {
      return 0;
    }
  }
  return 1;
}

int main(int argc, char **argv)
{
  char tmp[AS_MAX_PATH + 8u];
  size_t n;
  size_t i;
  int ok;
  if (argc == 2 && strcmp(argv[1], "--version") == 0) {
    return printf("ivs_asm %s\n", AS_VERSION) > 0 && fflush(stdout) == 0 ? 0 : 1;
  }
  n = argc == 3 ? strlen(argv[2]) : 0u;
  if (argc != 3 || !as_path_ok(argv[1]) || n == 0u || n > AS_MAX_PATH || strcmp(argv[1], argv[2]) == 0) {
    fprintf(stderr, "usage: ivs_asm <source.asm> <listing.txt>   (a relative source path of A-Z a-z 0-9 . _ / - "
                    "that is not the listing path)\n       ivs_asm --version\n");
    return 1;
  }
  memcpy(tmp, argv[2], n);
  memcpy(tmp + n, ".tmp", 5u);
  as_g.src = argv[1];
  if (as_load(argv[1])) {
    as_header();
  }
  if (!as_g.failed) {
    as_pass(1u);
  }
  if (!as_g.failed && as_g.nwords == 0u) {
    as_g.lineno = 0ul;
    as_fail("asm-syntax", "the source holds no word", "");
  }
  if (as_g.failed) {
    return 1;
  }
  if ((as_g.out = fopen(tmp, "wb")) == NULL) {
    fprintf(stderr, "ivs_asm: cannot create %s\n", tmp);
    return 1;
  }
  for (i = 0u; i < as_g.nhdr; i++) {
    fprintf(as_g.out, "%s\n", as_g.line[i]);
  }
  fprintf(as_g.out, "# generated by ivs_asm from %s; edit the source, not this file\n", as_g.src);
  for (i = 0u; i < as_g.nsym; i++) {
    if (as_g.sym[i].is_label) {
      fprintf(as_g.out, "# sym: %s %04X\n", as_g.sym[i].name, (unsigned)as_g.sym[i].value);
    }
  }
  as_pass(2u);
  ok = !as_g.failed && ferror(as_g.out) == 0;
  ok = fclose(as_g.out) == 0 && ok;
  if (ok && rename(tmp, argv[2]) != 0) {
    ok = 0;
  }
  if (!ok) {
    if (!as_g.failed) {
      fprintf(stderr, "ivs_asm: write error on %s\n", argv[2]);
    }
    remove(tmp);
  }
  return ok ? 0 : 1;
}
