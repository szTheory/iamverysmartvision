/* How a mnemonic places its operands in the decle (the shape letters of as_shapes say what each is). */
enum {
  AK_NONE,    /* the decle is the base */
  AK_R0,      /* base | Rd */
  AK_R3,      /* base | Rs << 3 (JR) */
  AK_RSAME,   /* base | Rd << 3 | Rd (TSTR, CLRR) */
  AK_RR,      /* base | Rs << 3 | Rd */
  AK_SHIFT,   /* base | N << 2 | R, the count 1 or 2 optional (R0 to R3) */
  AK_SMALL,   /* base | n, n 0 or 1, 0 when absent (NOP, SIN) */
  AK_IMM,     /* base | Rd, then the immediate (two byte words after SDBD) */
  AK_DIR_OUT, /* MVO Rs, address */
  AK_DIR_IN,  /* MVI address, Rd and the other five direct rows */
  AK_IND_OUT, /* MVO@ Rs, Rptr */
  AK_IND_IN,  /* MVI@ Rptr, Rd and the other five indirect rows */
  AK_BRANCH,  /* conditional branch, target */
  AK_BEXT,    /* BEXT target, code */
  AK_NOPP,    /* the two-word no-operation branch */
  AK_JUMP,    /* J, JE, JD: target */
  AK_JSR,     /* JSR, JSRE, JSRD: R4 to R6, target */
  AK_SDBD     /* the prefix */
};

/* Operands of a kind, one letter each: r register, # immediate, a address or target, n number; an
 * upper-case letter is an optional trailing operand. Pass 1 uses the kind only (syntax alone, D-17). */
static const char *const as_shapes[] = {
  [AK_NONE] = "", [AK_R0] = "r", [AK_R3] = "r", [AK_RSAME] = "r", [AK_RR] = "rr", [AK_SHIFT] = "rN",
  [AK_SMALL] = "N", [AK_IMM] = "#r", [AK_DIR_OUT] = "ra", [AK_DIR_IN] = "ar", [AK_IND_OUT] = "rr",
  [AK_IND_IN] = "rr", [AK_BRANCH] = "a", [AK_BEXT] = "an", [AK_NOPP] = "", [AK_JUMP] = "a", [AK_JSR] = "ra",
  [AK_SDBD] = "",
};

typedef struct as_op {
  const char *name;
  unsigned kind;
  unsigned rmax; /* highest register number the register operand may name */
  unsigned base; /* decle bits fixed by the mnemonic (for a jump, the DE field of its second decle) */
} as_op;          /* the leaf row id of the first decle is the mnemonic (every jump form is row J) */

