/* ---- all three slots ---- */

/* EXEC, GROM and a cartridge loaded in each of the six orders give one composite digest and one
 * instance image. */
static int ml_order_free(void)
{
  static const uint32_t orders[6][3] = {{1u, 2u, 3u}, {1u, 3u, 2u}, {2u, 1u, 3u},
                                        {2u, 3u, 1u}, {3u, 1u, 2u}, {3u, 2u, 1u}};
  uint8_t first[32];
  uint8_t *first_storage = malloc(IVS_MACHINE_BYTES);
  uint32_t k;
  int rc = IVS_TEST_PASS;
  IVS_CHECK(first_storage != NULL);
  for (k = 0u; k < 6u && rc == IVS_TEST_PASS; k++) {
    ml_inst x;
    ivs_load_report reps[3];
    uint8_t d[32];
    if (!ml_new(&x)) {
      rc = IVS_TEST_FAIL;
      break;
    }
    if (!ml_load_all(&x, orders[k], reps) || ivs_machine_state_digest(x.m, IVS_DIGEST_COMPOSITE, d) != IVS_OK) {
      rc = IVS_TEST_FAIL;
    } else if (k == 0u) {
      memcpy(first, d, sizeof first);
      memcpy(first_storage, x.storage, IVS_MACHINE_BYTES);
    } else if (!ml_same(first, d, 32u) || !ml_same(first_storage, x.storage, IVS_MACHINE_BYTES)) {
      ivs_test_diag("order %u differs from order 0", (unsigned)k);
      rc = IVS_TEST_FAIL;
    }
    ml_free(&x);
  }
  free(first_storage);
  return rc;
}

/* With all three slots loaded, info reports each slot exactly as its load report did. */
static int ml_info_all_slots(void)
{
  static const uint32_t order[3] = {3u, 1u, 2u};
  ivs_load_report reps[3];
  ivs_info info;
  ml_inst x;
  uint32_t k;
  int rc = IVS_TEST_FAIL;
  IVS_CHECK(ml_new(&x));
  memset(&info, 0, sizeof info);
  info.struct_size = (uint32_t)sizeof info;
  if (ml_load_all(&x, order, reps) && ivs_machine_info(x.m, &info) == IVS_OK) {
    rc = IVS_TEST_PASS;
    for (k = 0u; k < 3u; k++) {
      if (info.slots[k].loaded != 1u || info.slots[k].kind != k + 1u ||
          !ml_same((const uint8_t *)&info.slots[k], (const uint8_t *)&reps[k].image, sizeof reps[k].image)) {
        ivs_test_diag("slot %u differs from its load report", (unsigned)k);
        rc = IVS_TEST_FAIL;
      }
    }
  }
  ml_free(&x);
  return rc;
}

/* Loading all three and unloading all three gives the fresh digest and the fresh instance bytes. */
static int ml_all_unload_all_fresh(void)
{
  static const uint32_t order[3] = {1u, 2u, 3u};
  ivs_load_report reps[3];
  ml_inst x;
  ml_inst fresh;
  uint8_t d0[32];
  uint8_t d1[32];
  int rc = IVS_TEST_FAIL;
  IVS_CHECK(ml_new(&x));
  if (!ml_new(&fresh)) {
    ml_free(&x);
    return IVS_TEST_FAIL;
  }
  if (!ml_load_all(&x, order, reps) || ivs_machine_unload(x.m, IVS_KIND_GROM) != IVS_OK ||
      ivs_machine_unload(x.m, IVS_KIND_CARTRIDGE) != IVS_OK || ivs_machine_unload(x.m, IVS_KIND_EXEC) != IVS_OK ||
      ivs_machine_state_digest(x.m, IVS_DIGEST_COMPOSITE, d1) != IVS_OK ||
      ivs_machine_state_digest(fresh.m, IVS_DIGEST_COMPOSITE, d0) != IVS_OK) {
    ivs_test_diag("load, unload or digest failed");
  } else if (!ml_same(d0, d1, 32u)) {
    ivs_test_diag("digest after unloading everything differs from the fresh digest");
  } else if (!ml_same(x.storage, fresh.storage, IVS_MACHINE_BYTES)) {
    ivs_test_diag("instance bytes after unloading everything differ from a fresh instance");
  } else {
    rc = IVS_TEST_PASS;
  }
  ml_free(&fresh);
  ml_free(&x);
  return rc;
}

