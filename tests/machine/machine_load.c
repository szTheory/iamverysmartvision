#define IVS_CHECK(cond)                                                                                \
  do {                                                                                                 \
    if (!(cond)) {                                                                                     \
      ivs_test_diag("check failed at line %d: %s", __LINE__, #cond);                                   \
      return IVS_TEST_FAIL;                                                                            \
    }                                                                                                  \
  } while (0)

#define ML_PROFILE "intv-2609-ntsc-family-p1"
#define ML_EXEC_BYTES 8192u
#define ML_GROM_BYTES 2048u

/* `cmake -E sha256sum exec.bin` over the EXEC stand-in. */
static const uint8_t ml_exec_sha[32] = {0xe1u, 0xa0u, 0xeeu, 0xd9u, 0x6du, 0xa8u, 0x9au, 0xf0u, 0xf8u, 0x5au, 0xe8u,
                                        0x02u, 0x7bu, 0x46u, 0x16u, 0x69u, 0x32u, 0x0bu, 0x22u, 0xf9u, 0xa4u, 0xc1u,
                                        0xc7u, 0xffu, 0x20u, 0xe6u, 0x27u, 0xe6u, 0xd2u, 0xd2u, 0xeeu, 0xe2u};

/* `cmake -E sha256sum grom.bin` over the GROM stand-in. */
static const uint8_t ml_grom_sha[32] = {0xdfu, 0xffu, 0x79u, 0x5au, 0x6bu, 0x8cu, 0xdfu, 0x42u, 0x1eu, 0x2eu, 0x08u,
                                        0x15u, 0x98u, 0x7bu, 0xa9u, 0xeeu, 0xd2u, 0x46u, 0xa3u, 0x47u, 0x4eu, 0xe2u,
                                        0x6au, 0xefu, 0xf7u, 0xe7u, 0x0fu, 0x0fu, 0x2eu, 0x5cu, 0xc1u, 0x6bu};

/* One instance in exact-size heap storage. */
typedef struct ml_inst {
  uint8_t *storage;
  ivs_machine *m;
} ml_inst;

static int ml_new(ml_inst *x)
{
  ivs_create_options o;
  memset(&o, 0, sizeof o);
  o.struct_size = (uint32_t)sizeof o;
  o.profile_id = ML_PROFILE;
  x->m = NULL;
  x->storage = malloc(IVS_MACHINE_BYTES);
  if (x->storage == NULL) {
    return 0;
  }
  memset(x->storage, 0xA5, IVS_MACHINE_BYTES);
  if (ivs_machine_create(&o, x->storage, IVS_MACHINE_BYTES, &x->m) != IVS_OK) {
    free(x->storage);
    x->storage = NULL;
    return 0;
  }
  return 1;
}

static void ml_free(ml_inst *x)
{
  free(x->storage);
  x->storage = NULL;
  x->m = NULL;
}

static uint16_t ml_exec_word(uint32_t i)
{
  return (uint16_t)((37u * i + 11u) & 0x3FFu);
}

/* The EXEC stand-in in a fresh heap buffer of exactly 8192 bytes. */
static uint8_t *ml_exec_image(void)
{
  uint8_t *b = malloc(ML_EXEC_BYTES);
  uint32_t i;
  if (b == NULL) {
    return NULL;
  }
  for (i = 0u; i < ML_EXEC_BYTES / 2u; i++) {
    b[2u * i] = (uint8_t)(ml_exec_word(i) >> 8);
    b[2u * i + 1u] = (uint8_t)(ml_exec_word(i) & 0xFFu);
  }
  return b;
}

static ivs_load_report ml_report(void)
{
  ivs_load_report r;
  memset(&r, 0xA5, sizeof r);
  r.struct_size = (uint32_t)sizeof r;
  return r;
}

static uint16_t ml_bus(const ml_inst *x, uint16_t addr)
{
  return ivs_memsys_read(&((const struct ivs_machine *)(const void *)x->m)->mem, addr);
}

static int ml_same(const uint8_t *a, const uint8_t *b, size_t n)
{
  return memcmp(a, b, n) == 0;
}

/* The fixed fields of a successful report. */
static int ml_report_ok(const ivs_load_report *r, uint32_t kind, uint32_t len, uint32_t units, uint32_t bits,
                        uint32_t base, const uint8_t sha[32])
{
  const ivs_image_report *s = &r->image;
  IVS_CHECK(r->struct_size == (uint32_t)sizeof *r);
  IVS_CHECK(r->reason == IVS_REASON_NONE);
  IVS_CHECK(r->segment_index == IVS_SEGMENT_NONE);
  IVS_CHECK(r->missing_features == 0u);
  IVS_CHECK(r->byte_offset == 0u);
  IVS_CHECK(s->struct_size == (uint32_t)sizeof *s);
  IVS_CHECK(s->kind == kind);
  IVS_CHECK(s->loaded == 1u);
  IVS_CHECK(s->length_bytes == len);
  IVS_CHECK(s->length_units == units);
  IVS_CHECK(s->unit_bits == bits);
  IVS_CHECK(s->base_addr == base);
  IVS_CHECK(s->reserved == 0u);
  IVS_CHECK(ml_same(s->sha256, sha, 32u));
  return IVS_TEST_PASS;
}

/* ---- tracer: EXEC ---- */

/* A stand-in EXEC loads OK: the report carries its length, units, width, base and the literal
 * digest; info reports the same slot; the bus reads its words at $1000..$1FFF. */
static int ml_exec_ok(void)
{
  ml_inst x;
  ivs_load_report r = ml_report();
  ivs_info info;
  int rc = IVS_TEST_FAIL;
  uint8_t *img = ml_exec_image();
  IVS_CHECK(img != NULL);
  if (!ml_new(&x)) {
    free(img);
    return IVS_TEST_FAIL;
  }
  memset(&info, 0, sizeof info);
  info.struct_size = (uint32_t)sizeof info;
  if (ivs_machine_load(x.m, IVS_KIND_EXEC, img, ML_EXEC_BYTES, NULL, &r) != IVS_OK) {
    ivs_test_diag("load refused, reason %u", (unsigned)r.reason);
  } else if (ml_report_ok(&r, IVS_KIND_EXEC, 8192u, 4096u, 10u, 0x1000u, ml_exec_sha) != IVS_TEST_PASS) {
    ivs_test_diag("report wrong");
  } else if (ivs_machine_info(x.m, &info) != IVS_OK ||
             !ml_same((const uint8_t *)&info.slots[0], (const uint8_t *)&r.image, sizeof r.image)) {
    ivs_test_diag("info slot differs from the report");
  } else if (ml_bus(&x, 0x1000u) != ml_exec_word(0u) || ml_bus(&x, 0x1001u) != ml_exec_word(1u) ||
             ml_bus(&x, 0x1FFFu) != ml_exec_word(4095u)) {
    ivs_test_diag("bus reads %04x at $1000, want %04x", (unsigned)ml_bus(&x, 0x1000u), (unsigned)ml_exec_word(0u));
  } else if (info.slots[1].loaded != 0u || info.slots[2].loaded != 0u) {
    ivs_test_diag("another slot reports loaded");
  } else {
    rc = IVS_TEST_PASS;
  }
  ml_free(&x);
  free(img);
  return rc;
}

/* Load then unload: the composite digest and every instance byte equal a fresh instance's; a
 * second unload of the empty slot is OK. */
static int ml_exec_unload_fresh(void)
{
  ml_inst x;
  ml_inst fresh;
  uint8_t d0[32];
  uint8_t d1[32];
  uint8_t d2[32];
  int rc = IVS_TEST_FAIL;
  uint8_t *img = ml_exec_image();
  IVS_CHECK(img != NULL);
  if (!ml_new(&x)) {
    free(img);
    return IVS_TEST_FAIL;
  }
  if (!ml_new(&fresh)) {
    ml_free(&x);
    free(img);
    return IVS_TEST_FAIL;
  }
  if (ivs_machine_state_digest(x.m, IVS_DIGEST_COMPOSITE, d0) != IVS_OK ||
      ivs_machine_load(x.m, IVS_KIND_EXEC, img, ML_EXEC_BYTES, NULL, NULL) != IVS_OK ||
      ivs_machine_state_digest(x.m, IVS_DIGEST_COMPOSITE, d1) != IVS_OK) {
    ivs_test_diag("load or digest failed");
  } else if (ml_same(d0, d1, 32u)) {
    ivs_test_diag("the load did not change the digest");
  } else if (ivs_machine_unload(x.m, IVS_KIND_EXEC) != IVS_OK ||
             ivs_machine_state_digest(x.m, IVS_DIGEST_COMPOSITE, d2) != IVS_OK) {
    ivs_test_diag("unload or digest failed");
  } else if (!ml_same(d0, d2, 32u)) {
    ivs_test_diag("digest after unload differs from the fresh digest");
  } else if (!ml_same(x.storage, fresh.storage, IVS_MACHINE_BYTES)) {
    ivs_test_diag("instance bytes after unload differ from a fresh instance");
  } else if (ivs_machine_unload(x.m, IVS_KIND_EXEC) != IVS_OK) {
    ivs_test_diag("unload of an empty slot refused");
  } else if (ml_bus(&x, 0x1000u) != ml_bus(&fresh, 0x1000u)) {
    ivs_test_diag("bus still reads the image after unload");
  } else {
    rc = IVS_TEST_PASS;
  }
  ml_free(&fresh);
  ml_free(&x);
  free(img);
  return rc;
}

/* ---- helpers for GROM, cartridges and refusals ---- */

/* The GROM stand-in in a fresh heap buffer of exactly 2048 bytes. */
static uint8_t *ml_grom_image(void)
{
  uint8_t *b = malloc(ML_GROM_BYTES);
  uint32_t i;
  if (b == NULL) {
    return NULL;
  }
  for (i = 0u; i < ML_GROM_BYTES; i++) {
    b[i] = (uint8_t)((7u * i + 3u) & 0xFFu);
  }
  return b;
}

/* The fixture record id of the generated table, or NULL. */
static const ivs_cart_fixture *ml_fixture(const char *id)
{
  size_t i;
  for (i = 0u; i < ivs_cart_count; i++) {
    if (strcmp(ivs_cart_table[i].id, id) == 0) {
      return &ivs_cart_table[i];
    }
  }
  return NULL;
}

/* A positive fixture's container in a fresh heap buffer of exactly its size. */
static uint8_t *ml_fixture_bytes(const ivs_cart_fixture *f)
{
  uint8_t *b;
  if (f == NULL || f->kind != IVS_CART_POSITIVE || f->n_bytes == 0u) {
    return NULL;
  }
  b = malloc(f->n_bytes);
  if (b != NULL) {
    memcpy(b, f->bytes, f->n_bytes);
  }
  return b;
}

/* A generated cartridge word: a 10-bit value that differs between segments and positions. */
static uint16_t ml_cart_word(uint32_t seg, uint32_t k)
{
  return (uint16_t)((97u * seg + 13u * k + 5u) & 0x3FFu);
}

static void ml_put16(uint8_t *p, uint32_t v)
{
  p[0] = (uint8_t)((v >> 8) & 0xFFu);
  p[1] = (uint8_t)(v & 0xFFu);
}

static void ml_put32(uint8_t *p, uint32_t v)
{
  ml_put16(p, v >> 16);
  ml_put16(p + 2, v & 0xFFFFu);
}

typedef struct ml_seg {
  uint32_t addr;
  uint32_t len_words;
} ml_seg;

/* An IVSC v1 container of the given segments (words from ml_cart_word) and required_features,
 * sealed with the core SHA-256, in a fresh heap buffer of exactly its size. */
static uint8_t *ml_cart_build(const ml_seg *segs, uint32_t n, uint32_t features, size_t *out_len)
{
  static const uint8_t magic[8] = {0x89u, 0x49u, 0x56u, 0x53u, 0x43u, 0x0Du, 0x0Au, 0x1Au};
  size_t words = 0u;
  size_t total;
  size_t at;
  uint32_t i;
  uint32_t k;
  uint8_t *b;
  for (i = 0u; i < n; i++) {
    words += segs[i].len_words;
  }
  total = IVS_IVSC_PREFIX_BYTES + IVS_IVSC_ENTRY_BYTES * (size_t)n + 2u * words + IVS_IVSC_TRAILER_BYTES;
  b = malloc(total);
  if (b == NULL) {
    return NULL;
  }
  memset(b, 0, total);
  memcpy(b, magic, sizeof magic);
  ml_put16(b + 8, 1u);
  ml_put32(b + 12, features);
  ml_put32(b + 16, (uint32_t)total);
  ml_put16(b + 20, n);
  at = IVS_IVSC_PREFIX_BYTES + IVS_IVSC_ENTRY_BYTES * (size_t)n;
  for (i = 0u; i < n; i++) {
    uint8_t *e = b + IVS_IVSC_PREFIX_BYTES + IVS_IVSC_ENTRY_BYTES * i;
    ml_put16(e, segs[i].addr);
    ml_put16(e + 2, segs[i].len_words);
    e[4] = (uint8_t)IVS_IVSC_WIDTH_BITS;
    for (k = 0u; k < segs[i].len_words; k++) {
      ml_put16(b + at, ml_cart_word(i, k));
      at += 2u;
    }
  }
  ivs_sha256_digest(b, total - IVS_IVSC_TRAILER_BYTES, b + total - IVS_IVSC_TRAILER_BYTES);
  *out_len = total;
  return b;
}

/* The registry record of the test profile. */
static const ivs_profile_desc *ml_profile(void)
{
  uint32_t index = 0u;
  if (ivs_machine_profile_lookup(ML_PROFILE, &index) != IVS_OK) {
    return NULL;
  }
  return ivs_profile_get(index);
}

/* A refused load: the status, the detail fields, an all-zero image and an instance left byte for
 * byte as it was (D-12). The report starts poisoned, so every field it checks was written. */
static int ml_refused(ml_inst *x, uint32_t kind, const uint8_t *b, size_t len, const ivs_load_options *opts,
                      ivs_status want, uint32_t reason, uint32_t seg, uint64_t off, uint32_t missing)
{
  static const uint8_t zero[sizeof(ivs_image_report)] = {0};
  ivs_load_report r = ml_report();
  ivs_status st;
  int rc = IVS_TEST_FAIL;
  uint8_t *before = malloc(IVS_MACHINE_BYTES);
  IVS_CHECK(before != NULL);
  memcpy(before, x->storage, IVS_MACHINE_BYTES);
  st = ivs_machine_load(x->m, kind, b, len, opts, &r);
  if (st != want) {
    ivs_test_diag("status %s, want %s (reason %u)", ivs_status_name(st), ivs_status_name(want), (unsigned)r.reason);
  } else if (r.struct_size != (uint32_t)sizeof r || r.reason != reason || r.segment_index != seg ||
             r.byte_offset != off || r.missing_features != missing) {
    ivs_test_diag("detail: reason %u seg %u off %llu missing 0x%X, want %u %u %llu 0x%X", (unsigned)r.reason,
                  (unsigned)r.segment_index, (unsigned long long)r.byte_offset, (unsigned)r.missing_features,
                  (unsigned)reason, (unsigned)seg, (unsigned long long)off, (unsigned)missing);
  } else if (!ml_same((const uint8_t *)&r.image, zero, sizeof zero)) {
    ivs_test_diag("a refused report carries an image");
  } else if (!ml_same(before, x->storage, IVS_MACHINE_BYTES)) {
    ivs_test_diag("the refused load changed the instance");
  } else {
    rc = IVS_TEST_PASS;
  }
  free(before);
  return rc;
}

/* Loads the three stand-ins (EXEC, GROM, the P02 container) in the order given (kinds). */
static int ml_load_all(ml_inst *x, const uint32_t order[3], ivs_load_report reps[3])
{
  const ivs_cart_fixture *f = ml_fixture("ivsc.P02-two-segments");
  uint8_t *exec = ml_exec_image();
  uint8_t *grom = ml_grom_image();
  uint8_t *cart = ml_fixture_bytes(f);
  int ok = exec != NULL && grom != NULL && cart != NULL;
  uint32_t i;
  for (i = 0u; ok && i < 3u; i++) {
    uint32_t kind = order[i];
    ivs_load_report *r = &reps[kind - 1u];
    const uint8_t *b = kind == IVS_KIND_EXEC ? exec : kind == IVS_KIND_GROM ? grom : cart;
    size_t len = kind == IVS_KIND_EXEC ? ML_EXEC_BYTES : kind == IVS_KIND_GROM ? ML_GROM_BYTES : f->n_bytes;
    *r = ml_report();
    if (ivs_machine_load(x->m, kind, b, len, NULL, r) != IVS_OK) {
      ivs_test_diag("load of kind %u refused, reason %u", (unsigned)kind, (unsigned)r->reason);
      ok = 0;
    }
  }
  free(exec);
  free(grom);
  free(cart);
  return ok;
}

/* ---- GROM ---- */

/* The GROM stand-in loads with 2048 8-bit units at $3000 and the literal digest; every byte
 * reads back at $3000..$37FF. */
static int ml_grom_ok(void)
{
  ml_inst x;
  ivs_load_report r = ml_report();
  int rc = IVS_TEST_FAIL;
  uint32_t i;
  uint8_t *img = ml_grom_image();
  IVS_CHECK(img != NULL);
  if (!ml_new(&x)) {
    free(img);
    return IVS_TEST_FAIL;
  }
  if (ivs_machine_load(x.m, IVS_KIND_GROM, img, ML_GROM_BYTES, NULL, &r) != IVS_OK) {
    ivs_test_diag("load refused, reason %u", (unsigned)r.reason);
  } else if (ml_report_ok(&r, IVS_KIND_GROM, 2048u, 2048u, 8u, 0x3000u, ml_grom_sha) != IVS_TEST_PASS) {
    ivs_test_diag("report wrong");
  } else {
    rc = IVS_TEST_PASS;
    for (i = 0u; i < ML_GROM_BYTES; i++) {
      if (ml_bus(&x, (uint16_t)(0x3000u + i)) != img[i]) {
        ivs_test_diag("bus reads %04x at $%04x, want %02x", (unsigned)ml_bus(&x, (uint16_t)(0x3000u + i)),
                      (unsigned)(0x3000u + i), (unsigned)img[i]);
        rc = IVS_TEST_FAIL;
        break;
      }
    }
  }
  ml_free(&x);
  free(img);
  return rc;
}

/* Load and unload GROM alone: the digest and every instance byte equal a fresh instance's. */
static int ml_grom_unload_fresh(void)
{
  ml_inst x;
  ml_inst fresh;
  uint8_t d0[32];
  uint8_t d1[32];
  int rc = IVS_TEST_FAIL;
  uint8_t *img = ml_grom_image();
  IVS_CHECK(img != NULL);
  if (!ml_new(&x)) {
    free(img);
    return IVS_TEST_FAIL;
  }
  if (!ml_new(&fresh)) {
    ml_free(&x);
    free(img);
    return IVS_TEST_FAIL;
  }
  if (ivs_machine_state_digest(fresh.m, IVS_DIGEST_COMPOSITE, d0) != IVS_OK ||
      ivs_machine_load(x.m, IVS_KIND_GROM, img, ML_GROM_BYTES, NULL, NULL) != IVS_OK ||
      ivs_machine_unload(x.m, IVS_KIND_GROM) != IVS_OK ||
      ivs_machine_state_digest(x.m, IVS_DIGEST_COMPOSITE, d1) != IVS_OK) {
    ivs_test_diag("load, unload or digest failed");
  } else if (!ml_same(d0, d1, 32u)) {
    ivs_test_diag("digest after unload differs from the fresh digest");
  } else if (!ml_same(x.storage, fresh.storage, IVS_MACHINE_BYTES)) {
    ivs_test_diag("instance bytes after unload differ from a fresh instance");
  } else {
    rc = IVS_TEST_PASS;
  }
  ml_free(&fresh);
  ml_free(&x);
  free(img);
  return rc;
}

/* ---- cartridges ---- */

/* The P01 container loads: the report carries the file length, the decle count, width 10, the
 * first segment's address and the typed whole-file digest; that address reads the word and the
 * next one reads the undriven 0xFFFF. */
static int ml_cart_ok(void)
{
  const ivs_cart_fixture *f = ml_fixture("ivsc.P01-min");
  ml_inst x;
  ivs_load_report r = ml_report();
  int rc = IVS_TEST_FAIL;
  uint8_t *img;
  uint32_t addr;
  uint32_t units = 0u;
  uint16_t word;
  size_t i;
  IVS_CHECK(f != NULL && f->n_segs == 1u && f->whole_sha256 != NULL);
  img = ml_fixture_bytes(f);
  IVS_CHECK(img != NULL);
  for (i = 0u; i < f->n_segs; i++) {
    units += f->segs[i].len_words;
  }
  addr = f->segs[0].addr;
  /* The first data word follows the prefix and the one entry. */
  word = (uint16_t)(((uint32_t)img[IVS_IVSC_PREFIX_BYTES + IVS_IVSC_ENTRY_BYTES] << 8) |
                    img[IVS_IVSC_PREFIX_BYTES + IVS_IVSC_ENTRY_BYTES + 1u]);
  if (!ml_new(&x)) {
    free(img);
    return IVS_TEST_FAIL;
  }
  if (ivs_machine_load(x.m, IVS_KIND_CARTRIDGE, img, f->n_bytes, NULL, &r) != IVS_OK) {
    ivs_test_diag("load refused, reason %u", (unsigned)r.reason);
  } else if (ml_report_ok(&r, IVS_KIND_CARTRIDGE, (uint32_t)f->n_bytes, units, 10u, addr, f->whole_sha256) !=
             IVS_TEST_PASS) {
    ivs_test_diag("report wrong");
  } else if (ml_bus(&x, (uint16_t)addr) != word || ml_bus(&x, (uint16_t)(addr + 1u)) != 0xFFFFu) {
    ivs_test_diag("bus reads %04x %04x at $%04x, want %04x ffff", (unsigned)ml_bus(&x, (uint16_t)addr),
                  (unsigned)ml_bus(&x, (uint16_t)(addr + 1u)), (unsigned)addr, (unsigned)word);
  } else {
    rc = IVS_TEST_PASS;
  }
  ml_free(&x);
  free(img);
  return rc;
}

/* The reported digest is the whole file's (A-04), not the container's trailer: for P01 and P02
 * it equals the typed whole_sha256 and the core SHA-256 of all the bytes, and differs from the
 * last 32 bytes. */
static int ml_cart_whole_digest(void)
{
  static const char *const ids[2] = {"ivsc.P01-min", "ivsc.P02-two-segments"};
  uint32_t k;
  for (k = 0u; k < 2u; k++) {
    const ivs_cart_fixture *f = ml_fixture(ids[k]);
    ml_inst x;
    ivs_load_report r = ml_report();
    uint8_t whole[32];
    int ok = 0;
    uint8_t *img = ml_fixture_bytes(f);
    IVS_CHECK(img != NULL && f->whole_sha256 != NULL);
    ivs_sha256_digest(img, f->n_bytes, whole);
    if (!ml_new(&x)) {
      free(img);
      return IVS_TEST_FAIL;
    }
    if (ivs_machine_load(x.m, IVS_KIND_CARTRIDGE, img, f->n_bytes, NULL, &r) != IVS_OK) {
      ivs_test_diag("%s: load refused, reason %u", ids[k], (unsigned)r.reason);
    } else if (!ml_same(r.image.sha256, f->whole_sha256, 32u) || !ml_same(r.image.sha256, whole, 32u)) {
      ivs_test_diag("%s: the reported digest is not the whole-file digest", ids[k]);
    } else if (ml_same(r.image.sha256, img + f->n_bytes - IVS_IVSC_TRAILER_BYTES, 32u)) {
      ivs_test_diag("%s: the reported digest is the trailer", ids[k]);
    } else {
      ok = 1;
    }
    ml_free(&x);
    free(img);
    if (!ok) {
      return IVS_TEST_FAIL;
    }
  }
  return IVS_TEST_PASS;
}

/* One segment covering the whole registry span (49,152 words on this profile) loads; both ends
 * read their words. */
static int ml_cart_span_full(void)
{
  const ivs_profile_desc *p = ml_profile();
  ml_inst x;
  ivs_load_report r = ml_report();
  ml_seg seg;
  size_t len = 0u;
  int rc = IVS_TEST_FAIL;
  uint8_t *img;
  IVS_CHECK(p != NULL && p->has_cart_span != 0u);
  seg.addr = p->cart_lo;
  seg.len_words = (uint32_t)p->cart_hi - p->cart_lo + 1u;
  IVS_CHECK(seg.len_words == 49152u);
  img = ml_cart_build(&seg, 1u, 0u, &len);
  IVS_CHECK(img != NULL);
  if (!ml_new(&x)) {
    free(img);
    return IVS_TEST_FAIL;
  }
  if (ivs_machine_load(x.m, IVS_KIND_CARTRIDGE, img, len, NULL, &r) != IVS_OK) {
    ivs_test_diag("load refused, reason %u", (unsigned)r.reason);
  } else if (r.image.length_units != seg.len_words || r.image.base_addr != seg.addr ||
             r.image.length_bytes != (uint32_t)len) {
    ivs_test_diag("report units %u base %04x bytes %u", (unsigned)r.image.length_units, (unsigned)r.image.base_addr,
                  (unsigned)r.image.length_bytes);
  } else if (ml_bus(&x, (uint16_t)p->cart_lo) != ml_cart_word(0u, 0u) ||
             ml_bus(&x, (uint16_t)p->cart_hi) != ml_cart_word(0u, seg.len_words - 1u)) {
    ivs_test_diag("bus does not read the span's end words");
  } else {
    rc = IVS_TEST_PASS;
  }
  ml_free(&x);
  free(img);
  return rc;
}

/* A segment starting one word below the registry span is OUT_OF_RANGE (layer 2) with its index
 * and the byte offset of its entry; the instance is unchanged. */
static int ml_cart_out_of_span(void)
{
  const ivs_profile_desc *p = ml_profile();
  ml_inst x;
  ml_seg seg;
  size_t len = 0u;
  int rc;
  uint8_t *img;
  IVS_CHECK(p != NULL && p->has_cart_span != 0u && p->cart_lo > 0u);
  seg.addr = (uint32_t)p->cart_lo - 1u;
  seg.len_words = 2u;
  img = ml_cart_build(&seg, 1u, 0u, &len);
  IVS_CHECK(img != NULL);
  if (!ml_new(&x)) {
    free(img);
    return IVS_TEST_FAIL;
  }
  rc = ml_refused(&x, IVS_KIND_CARTRIDGE, img, len, NULL, IVS_E_OUT_OF_RANGE, IVS_REASON_OUT_OF_SPAN, 0u,
                  IVS_IVSC_PREFIX_BYTES, 0u);
  ml_free(&x);
  free(img);
  return rc;
}

/* The span's upper edge through the layer-2 seam with a synthetic span [$4000, $7FFF] (the
 * registered span ends at $FFFF, where the parser's address-wrap check fires first): a segment
 * ending on the last word is inside, one ending a word past it is not, in either table position. */
static int ml_cart_span_end(void)
{
  ivs_ivsc_view v;
  memset(&v, 0, sizeof v);
  v.segment_count = 1u;
  v.segs[0].addr = 0x7FFFu;
  v.segs[0].len_words = 1u;
  IVS_CHECK(ivs_machine_cart_span_check(0x4000u, 0x7FFFu, &v) == IVS_SEGMENT_NONE);
  v.segs[0].len_words = 2u;
  IVS_CHECK(ivs_machine_cart_span_check(0x4000u, 0x7FFFu, &v) == 0u);
  v.segs[0].addr = 0x4000u;
  v.segs[0].len_words = 0x4000u;
  IVS_CHECK(ivs_machine_cart_span_check(0x4000u, 0x7FFFu, &v) == IVS_SEGMENT_NONE);
  v.segs[0].len_words = 0x4001u;
  IVS_CHECK(ivs_machine_cart_span_check(0x4000u, 0x7FFFu, &v) == 0u);
  v.segs[0].addr = 0x3FFFu;
  v.segs[0].len_words = 1u;
  IVS_CHECK(ivs_machine_cart_span_check(0x4000u, 0x7FFFu, &v) == 0u);
  v.segment_count = 2u;
  v.segs[0].addr = 0x4000u;
  v.segs[0].len_words = 1u;
  v.segs[1].addr = 0x7FF0u;
  v.segs[1].len_words = 0x10u;
  IVS_CHECK(ivs_machine_cart_span_check(0x4000u, 0x7FFFu, &v) == IVS_SEGMENT_NONE);
  v.segs[1].len_words = 0x11u;
  IVS_CHECK(ivs_machine_cart_span_check(0x4000u, 0x7FFFu, &v) == 1u);
  return IVS_TEST_PASS;
}

/* A container requiring feature bit 0 (or bits 0 and 31) is UNSUPPORTED: the report carries
 * the missing bits and the offset of required_features; the instance is unchanged. */
static int ml_cart_feature(void)
{
  static const uint32_t masks[2] = {0x1u, 0x80000001u};
  const ivs_profile_desc *p = ml_profile();
  uint32_t k;
  IVS_CHECK(p != NULL && p->features_supported == 0u);
  for (k = 0u; k < 2u; k++) {
    ml_inst x;
    ml_seg seg;
    size_t len = 0u;
    int rc;
    uint8_t *img;
    seg.addr = p->cart_lo;
    seg.len_words = 4u;
    img = ml_cart_build(&seg, 1u, masks[k], &len);
    IVS_CHECK(img != NULL);
    if (!ml_new(&x)) {
      free(img);
      return IVS_TEST_FAIL;
    }
    rc = ml_refused(&x, IVS_KIND_CARTRIDGE, img, len, NULL, IVS_E_UNSUPPORTED, IVS_REASON_FEATURES,
                    IVS_SEGMENT_NONE, IVS_IVSC_FEATURES_OFFSET, masks[k]);
    ml_free(&x);
    free(img);
    if (rc != IVS_TEST_PASS) {
      return rc;
    }
  }
  return IVS_TEST_PASS;
}

/* ---- options ---- */

static ivs_load_options ml_opts(uint32_t flags, const uint8_t expect[32])
{
  ivs_load_options o;
  memset(&o, 0, sizeof o);
  o.struct_size = (uint32_t)sizeof o;
  o.flags = flags;
  if (expect != NULL) {
    memcpy(o.expect_sha256, expect, sizeof o.expect_sha256);
  }
  return o;
}

/* expect_sha256 equal to the image digest loads: the EXEC literal, and for a cartridge the
 * whole-file digest (not the trailer). */
static int ml_expect_ok(void)
{
  const ivs_cart_fixture *f = ml_fixture("ivsc.P01-min");
  ivs_load_options o = ml_opts(IVS_LOAD_F_EXPECT_SHA256, ml_exec_sha);
  ivs_load_options oc;
  ml_inst x;
  int rc = IVS_TEST_FAIL;
  uint8_t *img = ml_exec_image();
  uint8_t *cart = ml_fixture_bytes(f);
  if (img == NULL || cart == NULL || !ml_new(&x)) {
    free(img);
    free(cart);
    return IVS_TEST_FAIL;
  }
  oc = ml_opts(IVS_LOAD_F_EXPECT_SHA256, f->whole_sha256);
  if (ivs_machine_load(x.m, IVS_KIND_EXEC, img, ML_EXEC_BYTES, &o, NULL) != IVS_OK) {
    ivs_test_diag("EXEC with its digest expected was refused");
  } else if (ivs_machine_load(x.m, IVS_KIND_CARTRIDGE, cart, f->n_bytes, &oc, NULL) != IVS_OK) {
    ivs_test_diag("cartridge with its whole-file digest expected was refused");
  } else {
    rc = IVS_TEST_PASS;
  }
  ml_free(&x);
  free(img);
  free(cart);
  return rc;
}

/* A differing expect_sha256 is DIGEST_MISMATCH with the instance unchanged: the EXEC literal with
 * its last bit flipped, and for a cartridge its own trailer. */
static int ml_expect_mismatch(void)
{
  const ivs_cart_fixture *f = ml_fixture("ivsc.P01-min");
  uint8_t bad[32];
  ivs_load_options o;
  ivs_load_options oc;
  ml_inst x;
  int rc = IVS_TEST_FAIL;
  uint8_t *img = ml_exec_image();
  uint8_t *cart = ml_fixture_bytes(f);
  if (img == NULL || cart == NULL || !ml_new(&x)) {
    free(img);
    free(cart);
    return IVS_TEST_FAIL;
  }
  memcpy(bad, ml_exec_sha, sizeof bad);
  bad[31] ^= 0x01u;
  o = ml_opts(IVS_LOAD_F_EXPECT_SHA256, bad);
  oc = ml_opts(IVS_LOAD_F_EXPECT_SHA256, cart + f->n_bytes - IVS_IVSC_TRAILER_BYTES);
  if (ml_refused(&x, IVS_KIND_EXEC, img, ML_EXEC_BYTES, &o, IVS_E_DIGEST_MISMATCH, IVS_REASON_EXPECT_DIGEST,
                 IVS_SEGMENT_NONE, 0u, 0u) == IVS_TEST_PASS &&
      ml_refused(&x, IVS_KIND_CARTRIDGE, cart, f->n_bytes, &oc, IVS_E_DIGEST_MISMATCH, IVS_REASON_EXPECT_DIGEST,
                 IVS_SEGMENT_NONE, 0u, 0u) == IVS_TEST_PASS) {
    rc = IVS_TEST_PASS;
  }
  ml_free(&x);
  free(img);
  free(cart);
  return rc;
}

