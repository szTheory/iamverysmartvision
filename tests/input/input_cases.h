#define II_CHECK(cond)                                                                                 \
  do {                                                                                                 \
    if (!(cond)) {                                                                                     \
      ivs_test_diag("check failed at line %d: %s", __LINE__, #cond);                                   \
      goto done;                                                                                       \
    }                                                                                                  \
  } while (0)

#define II_POISON 0xA5u
/* Ticks that cover the two reads of stand-in program PORTS several times over. */
#define II_RUN_TICKS 4000u
/* Largest control count the fixed arrays of the family files hold (the literal has 31). */
#define II_MAX_CTL 32u

/* One control of the literal (generated by cmake/IvsInputProbes.cmake, one record per bit, index =
 * bit): lower case name, bit, the mask of bits a press clears, the byte a read returns with only that
 * control pressed (FF XOR cleared) and the connector pins it grounds (bit n = pin n). */
typedef struct ivs_ip_ctl {
  const char *name;
  uint8_t bit;
  uint8_t cleared;
  uint8_t byte;
  uint16_t pins;
} ivs_ip_ctl;
extern const ivs_ip_ctl ivs_ip_ctls[];
extern const size_t ivs_ip_count;

/* A family of cases: count, id and run by index (ids are unique across families). */
typedef struct ii_family {
  size_t (*count)(void);
  const char *(*id)(size_t i);
  int (*run)(size_t i);
} ii_family;
extern const ii_family ivs_input_fam_single;
extern const ii_family ivs_input_fam_combo;
extern const ii_family ivs_input_fam_port;
extern const ii_family ivs_input_fam_slice;

/* The source files of the suite for the TAP header (the controller literal and its SHA-256). */
const ivs_test_source *ivs_input_sources(size_t *n);

/* The accessor trio of a family made of a plain case table. */
#define II_TABLE_FAMILY(fam, table)                                                                    \
  static size_t fam##_count(void) { return sizeof table / sizeof table[0]; }                            \
  static const char *fam##_id(size_t i) { return table[i].id; }                                        \
  static int fam##_run(size_t i) { return table[i].fn(); }                                             \
  const ii_family ivs_input_fam_##fam = {fam##_count, fam##_id, fam##_run}

/* One event: words 0 and 1 (ports 0 and 1) at at_tick. */
static inline void ii_event(ivs_input_event *e, uint64_t at, uint32_t w0, uint32_t w1)
{
  memset(e, 0, sizeof *e);
  e->at_tick = at;
  e->controller[0] = w0;
  e->controller[1] = w1;
}

/* One run call to target with n events; the report is poisoned first (separate statements). */
static inline ivs_status ii_run(ivs_machine *m, uint64_t target, const ivs_input_event *ev, uint32_t n,
                                ivs_run_report *rep)
{
  ivs_run_request q;
  memset(&q, 0, sizeof q);
  q.struct_size = (uint32_t)sizeof q;
  q.target_ticks = target;
  q.events = ev;
  q.event_count = n;
  memset(rep, II_POISON, sizeof *rep);
  rep->struct_size = (uint32_t)sizeof *rep;
  return ivs_machine_run(m, &q, rep);
}

/* Peeks one word at addr; 0xFFFFFFFF when the peek refuses. */
static inline uint32_t ii_peek(const ivs_machine *m, uint16_t addr)
{
  uint16_t w = 0u;
  if (ivs_machine_peek(m, addr, 1u, &w) != IVS_OK) {
    return 0xFFFFFFFFu;
  }
  return w;
}

/* A powered instance that runs one unit per ii_rig_set call: the words in force change at the start of
 * the next unit (an event at the current machine time is applied at the first unit start at or above
 * it), so a peek or bus read after the call sees them. now is machine time at the last boundary. */
typedef struct ii_rig {
  ivs_ms_inst x;
  uint64_t now;
} ii_rig;

static inline int ii_rig_open(ii_rig *r, uint32_t program)
{
  r->now = 0u;
  return ivs_ms_powered_prog(&r->x, program, II_POISON);
}

static inline void ii_rig_close(ii_rig *r)
{
  ivs_ms_free(&r->x);
}

static inline struct ivs_machine *ii_im(ii_rig *r)
{
  return (struct ivs_machine *)(void *)r->x.storage;
}

/* Sets the words of ports 0 and 1 (one event, one unit). 1 on success. */
static inline int ii_rig_set(ii_rig *r, uint32_t w0, uint32_t w1)
{
  ivs_input_event ev;
  ivs_run_report rep;
  ivs_status st;
  ii_event(&ev, r->now, w0, w1);
  st = ii_run(r->x.m, r->now + 1u, &ev, 1u, &rep);
  if (st != IVS_OK || rep.units_executed != 1u || rep.input_consumed != 1u) {
    ivs_test_diag("rig set refused (%s), units %llu consumed %u", ivs_status_name(st),
                  (unsigned long long)rep.units_executed, (unsigned)rep.input_consumed);
    return 0;
  }
  r->now = rep.now_ticks;
  return 1;
}

/* A CPU read and a CPU write of the memory system of the rig's machine, through the bus function the
 * CPU itself uses. */
static inline uint16_t ii_bus_read(ii_rig *r, uint16_t addr)
{
  ivs_cp1610_access a;
  ivs_bus_reply rp;
  memset(&a, 0, sizeof a);
  a.kind = IVS_ACC_READ;
  a.addr = addr;
  rp = ivs_memsys_bus(&ii_im(r)->mem, &a);
  return rp.data;
}

static inline void ii_bus_write(ii_rig *r, uint16_t addr, uint16_t value)
{
  ivs_cp1610_access a;
  memset(&a, 0, sizeof a);
  a.kind = IVS_ACC_WRITE;
  a.addr = addr;
  a.data = value;
  (void)ivs_memsys_bus(&ii_im(r)->mem, &a);
}

#endif
